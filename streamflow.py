"""### Part 5 - Average U.S. Daily Birth Data

You will now create a graph using average daily birth data in the U.S.

### Numpy Array Creation & Slicing

Slice the array to create the x and y-axis values. These will correspond to the following columns in the CSV linked on the HW instructions page:

*   x - Date
*   y_1 - Births
"""

data = np.genfromtxt('2012-US-Birth-Rates.csv', delimiter=',', dtype=str, skip_header=1)

x = data[:, 0].astype('datetime64[D]')
y_1 = data[:, 1].astype(float)

"""### Graphing the Data

Plot x and y_1 with the elements shown in the instructions in the code block below.
"""

plt.figure(figsize=(12, 4))
plt.plot(x, y_1, color='lightseagreen')

def label(text, day, text_day, dy, rad):
    d = np.datetime64(day)
    yv = y_1[x == d][0]
    plt.annotate(text, xy=(d, yv), xytext=(np.datetime64(text_day), yv + dy),
                 arrowprops=dict(arrowstyle='->', lw=2, connectionstyle='arc3,rad=' + str(rad)))

label("New Year's Day", '2012-01-01', '2012-01-15', -80, 0.1)
label('4th of July', '2012-07-04', '2012-07-25', -100, 0.3)
label('Halloween', '2012-10-31', '2012-09-15', 0, -0.3)
label('Thanksgiving', '2012-11-22', '2012-10-25', -150, 0.3)
label('Christmas', '2012-12-25', '2012-11-08', 150, 0.3)

plt.title('Average U.S. Daily Birth Data')
plt.xlabel('Date')
plt.ylabel('Births')
plt.grid(True)
plt.show()

# Births drop on these holidays because a lot of births are scheduled ahead of time
# (C-sections and inductions), and doctors and families avoid scheduling them on holidays.